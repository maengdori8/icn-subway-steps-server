-- ---------------------------------------------------------------------
-- 시퀀스: id 번호표. allocationSize 1(한 번에 1씩). H2는 값을 32개씩 미리 잡아 두므로(CACHE 32)
-- 서버를 강제로 끄면 다음 번호가 건너뛸 수 있다. 표본 계정 101·102, 표본 팁 7·8은 시드가 번호를 직접 넣는다.
-- ---------------------------------------------------------------------
create sequence app_user_seq start with 103 increment by 1;

create sequence tip_seq start with 9 increment by 1;


-- ---------------------------------------------------------------------
-- route: 경로(EXPRESS · LOCAL · T2). 자연 키 code. 단계 수는 열이 아니라 route_step 개수로 센다.
-- ---------------------------------------------------------------------
create table route (
    available boolean not null,
    sort_order integer not null,
    code varchar(16) not null,
    name_en varchar(80) not null,
    name_ko varchar(80) not null,
    summary_en varchar(120) not null,
    summary_ko varchar(120) not null,
    primary key (code)
);


-- ---------------------------------------------------------------------
-- app_user: 계정. username UNIQUE. password_hash는 BCrypt 해시(60자)만 저장한다.
-- ---------------------------------------------------------------------
create table app_user (
    created_at timestamp(6) with time zone not null,
    id bigint not null,
    username varchar(24) not null unique,
    password_hash varchar(60) not null,
    primary key (id)
);


-- ---------------------------------------------------------------------
-- route_step: 경로의 한 단계. id는 IDENTITY(API에 내보내지 않음). 한 경로 안에서 step_no는 하나뿐.
-- elevator_en·elevator_ko는 현장 확인 전 null이며 둘 다 채워야 API가 준다.
-- ---------------------------------------------------------------------
create table route_step (
    step_no integer not null,
    id bigint generated by default as identity,
    route_code varchar(16) not null,
    photo_key varchar(40),
    sign_en varchar(80) not null,
    sign_ko varchar(80) not null,
    title_en varchar(120) not null,
    title_ko varchar(120) not null,
    elevator_en varchar(200),
    elevator_ko varchar(200),
    instructions_en varchar(1000) not null,
    instructions_ko varchar(1000) not null,
    icon enum ('ESCALATOR','PLANE','TRAIN') not null,
    role enum ('FIND','HERE') not null,
    primary key (id),
    unique (route_code, step_no)
);


-- ---------------------------------------------------------------------
-- tip: 단계에 붙는 팁. title·location 160, note 300은 코드 포인트 80·150자를 UTF-16 단위로 두 배 잡은 길이.
-- example에는 DB 기본값이 없다(서버가 false, 시드만 true). step_no는 route_step을 FK로 가리키지 않는다.
-- ---------------------------------------------------------------------
create table tip (
    example boolean not null,
    step_no integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint not null,
    owner_id bigint not null,
    verified_at timestamp(6) with time zone not null,
    route_code varchar(16) not null,
    location varchar(160) not null,
    title varchar(160) not null,
    note varchar(300),
    status enum ('OUTDATED','VERIFIED') not null,
    primary key (id)
);

-- 단계별 팁 목록(GET /api/tips?route=&step=)과 내 팁(GET /api/me/tips)용 인덱스
create index ix_tip_route_step
    on tip (route_code, step_no);

create index ix_tip_owner
    on tip (owner_id);


